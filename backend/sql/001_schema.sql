CREATE TABLE IF NOT EXISTS users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 role ENUM('elder','caregiver') NOT NULL,
 name VARCHAR(100) NOT NULL,
 birth_date DATE NOT NULL,
 phone VARCHAR(15) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS sessions (
 token_hash CHAR(64) PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL,
 expires_at DATETIME NOT NULL,
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
 INDEX(user_id), INDEX(expires_at)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rate_limits (
 bucket CHAR(64) PRIMARY KEY,
 attempts INT NOT NULL,
 reset_at DATETIME NOT NULL,
 INDEX(reset_at)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS care_links (
 elder_id BIGINT UNSIGNED NOT NULL,
 caregiver_id BIGINT UNSIGNED NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(elder_id, caregiver_id),
 FOREIGN KEY(elder_id) REFERENCES users(id),
 FOREIGN KEY(caregiver_id) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS link_codes (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 elder_id BIGINT UNSIGNED NOT NULL,
 code_hash CHAR(64) NOT NULL UNIQUE,
 expires_at DATETIME NOT NULL,
 revoked_at DATETIME NULL,
 used_at DATETIME NULL,
 FOREIGN KEY(elder_id) REFERENCES users(id),
 INDEX(elder_id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS medications (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 elder_id BIGINT UNSIGNED NOT NULL,
 name VARCHAR(100) NOT NULL,
 dosage VARCHAR(60) NOT NULL,
 start_date DATE NOT NULL,
 end_date DATE NOT NULL,
 active BOOLEAN NOT NULL DEFAULT TRUE,
 FOREIGN KEY(elder_id) REFERENCES users(id),
 INDEX(elder_id,active)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS medication_times (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 medication_id BIGINT UNSIGNED NOT NULL,
 time TIME NOT NULL,
 active BOOLEAN NOT NULL DEFAULT TRUE,
 UNIQUE(medication_id,time),
 FOREIGN KEY(medication_id) REFERENCES medications(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS dose_records (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 time_id BIGINT UNSIGNED NOT NULL,
 dose_date DATE NOT NULL,
 status ENUM('taken','pending') NOT NULL,
 recorded_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(time_id,dose_date),
 FOREIGN KEY(time_id) REFERENCES medication_times(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS appointments (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 elder_id BIGINT UNSIGNED NOT NULL,
 doctor VARCHAR(100) NOT NULL,
 specialty VARCHAR(100) NOT NULL,
 scheduled_at DATETIME NOT NULL,
 location VARCHAR(200) NOT NULL,
 cancelled BOOLEAN NOT NULL DEFAULT FALSE,
 FOREIGN KEY(elder_id) REFERENCES users(id),
 INDEX(elder_id,scheduled_at)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS contacts (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 elder_id BIGINT UNSIGNED NOT NULL,
 name VARCHAR(100) NOT NULL,
 phone VARCHAR(15) NOT NULL,
 relationship VARCHAR(60) NOT NULL,
 is_primary BOOLEAN NOT NULL DEFAULT FALSE,
 FOREIGN KEY(elder_id) REFERENCES users(id),
 INDEX(elder_id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS pains (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 elder_id BIGINT UNSIGNED NOT NULL,
 view ENUM('front','back') NOT NULL,
 region VARCHAR(60) NOT NULL,
 type VARCHAR(60) NOT NULL,
 intensity TINYINT UNSIGNED NOT NULL CHECK(intensity BETWEEN 1 AND 10),
 onset VARCHAR(60) NOT NULL,
 notes VARCHAR(1000) NOT NULL DEFAULT '',
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(elder_id) REFERENCES users(id),
 INDEX(elder_id,created_at)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS pain_views (
 pain_id BIGINT UNSIGNED NOT NULL,
 caregiver_id BIGINT UNSIGNED NOT NULL,
 viewed_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(pain_id,caregiver_id),
 FOREIGN KEY(pain_id) REFERENCES pains(id),
 FOREIGN KEY(caregiver_id) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS activities (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 elder_id BIGINT UNSIGNED NOT NULL,
 actor_id BIGINT UNSIGNED NOT NULL,
 action VARCHAR(60) NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(elder_id) REFERENCES users(id),
 FOREIGN KEY(actor_id) REFERENCES users(id),
 INDEX(elder_id,created_at)
) ENGINE=InnoDB;
