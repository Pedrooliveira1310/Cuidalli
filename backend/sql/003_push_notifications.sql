CREATE TABLE IF NOT EXISTS push_devices (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL,
 session_hash CHAR(64) NOT NULL,
 token_hash CHAR(64) NOT NULL UNIQUE,
 token TEXT NOT NULL,
 platform ENUM('android','web') NOT NULL,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id),
 FOREIGN KEY(session_hash) REFERENCES sessions(token_hash) ON DELETE CASCADE,
 INDEX(user_id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS push_outbox (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 device_id BIGINT UNSIGNED NOT NULL,
 elder_id BIGINT UNSIGNED NOT NULL,
 event_key VARCHAR(120) NOT NULL,
 title VARCHAR(100) NOT NULL,
 body VARCHAR(250) NOT NULL,
 attempts TINYINT UNSIGNED NOT NULL DEFAULT 0,
 next_attempt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 delivered_at DATETIME NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(device_id) REFERENCES push_devices(id) ON DELETE CASCADE,
 FOREIGN KEY(elder_id) REFERENCES users(id),
 UNIQUE(device_id,event_key),
 INDEX(delivered_at,next_attempt)
) ENGINE=InnoDB;
